Lemma mccommit_after_next : forall b,
  hwb_after b (fun key => observe_action_write (M.empty _) key (hwb_mccommit_decoded b)) = mccommit_next b.
Proof. intro b. kernel_refl. Qed.

Lemma mccommit_rule_next : forall b, rule_next (normalization_rule 10) b = mccommit_next b.
Proof.
  intro b. transitivity (hwb_after b (fun key => observe_action_write (M.empty _) key (hwb_mccommit_decoded b))).
  - unfold rule_next. apply hwb_after_ext. intro key. apply mccommit_observer.
  - apply mccommit_after_next.
Qed.

Theorem mccommit_enabled : forall b,
  evalExpr (((Var type (SyntaxKind (Bit 4)) (hw_mc_phase b)) == $$(natToWord 4 11)))%kami_expr = true ->
  exists u, eval_cpu_rule (hwb_regs b) (normalization_rule 10) = Some u /\
    M.union u (hwb_regs b) = hwb_regs (mccommit_next b).
Proof.
  intros b Hg.
  assert (He : exists u, eval_cpu_rule (hwb_regs b) (normalization_rule 10) = Some u).
  { unfold eval_cpu_rule. rewrite mccommit_rule_action. unfold mccommit_fetch_action.
    repeat first [progress cbn [eval_linear_action]
    | rewrite hwb_read_mc_phase
  | rewrite hwb_read_mc_write_base
  | rewrite hwb_read_mc_write_ptr
  | rewrite hwb_read_coupling_desc_next_id
  | rewrite hwb_read_coupling_desc_base_table
  | rewrite hwb_read_coupling_desc_count_table
  | rewrite hwb_read_coupling_desc_valid_table].
    repeat match goal with H : _ /\ _ |- _ => destruct H end.
    repeat match goal with H : evalExpr ?e = true |- context [if evalExpr ?e then _ else _] => rewrite H end.
    first [ (match goal with |- context [eval_linear_action ?o ?a] =>
               assert (T : total_from nil a) by apply mccommit_decoded_total;
               destruct (total_from_eval _ a nil o T) as [u [ret [E' _]]]; rewrite E'
             end; eexists; reflexivity)
          | (eexists; reflexivity) ]. }
  destruct He as [u Hu]. exists u. split; [exact Hu|].
  rewrite <- mccommit_rule_next. apply rule_next_correct; [|exact Hu].
  rewrite cpu_rules_listed. apply in_map. cbn [In]. auto 13.
Qed.

