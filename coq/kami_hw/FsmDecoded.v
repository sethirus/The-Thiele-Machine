Theorem lhdr_enabled : forall b,
  evalExpr (((Var type (SyntaxKind (Bit 3)) (hw_lassert_phase b)) == $$(WO~0~0~1)))%kami_expr = true ->
  exists u, eval_cpu_rule (hwb_regs b) (normalization_rule 1) = Some u /\
    M.union u (hwb_regs b) = hwb_regs (lhdr_next b).
Proof.
  intros b Hg.
  assert (He : exists u, eval_cpu_rule (hwb_regs b) (normalization_rule 1) = Some u).
  { unfold eval_cpu_rule. rewrite lhdr_rule_action. unfold lhdr_fetch_action.
    repeat first [progress cbn [eval_linear_action]
    | rewrite hwb_read_lassert_phase
  | rewrite hwb_read_mem
  | rewrite hwb_read_lassert_fbase].
    repeat match goal with H : _ /\ _ |- _ => destruct H end.
    repeat match goal with H : evalExpr ?e = true |- context [if evalExpr ?e then _ else _] => rewrite H end.
    first [ (match goal with |- context [eval_linear_action ?o ?a] =>
               assert (T : total_from nil a) by apply lhdr_decoded_total;
               destruct (total_from_eval _ a nil o T) as [u [ret [E' _]]]; rewrite E'
             end; eexists; reflexivity)
          | (eexists; reflexivity) ]. }
  destruct He as [u Hu]. exists u. split; [exact Hu|].
  rewrite <- lhdr_rule_next. apply rule_next_correct; [|exact Hu].
  rewrite cpu_rules_listed. apply in_map. cbn [In]. auto 13.
Qed.

