Definition mccopy_decoded (mc_phase_v : type (Bit 4)) (mc_i_v : type (Bit CouplingPairCountSz)) (mc_j_v : type (Bit CouplingPairCountSz)) (mc_src1_base_v : type (Bit CouplingPairIdxSz)) (mc_src1_count_v : type (Bit CouplingPairCountSz)) (mc_src2_base_v : type (Bit CouplingPairIdxSz)) (mc_src2_count_v : type (Bit CouplingPairCountSz)) (mc_write_ptr_v : type (Bit DescTableNextIdSz)) (coupling_pair_src_table_v : type (Vector (Bit WordSz) CouplingPairIdxSz)) (coupling_pair_dst_table_v : type (Vector (Bit WordSz) CouplingPairIdxSz)) (coupling_pair_valid_table_v : type (Vector Bool CouplingPairIdxSz)) (mc_err_v : type (Bool)) (mc_error_v : type (Bit WordSz)) : ActionT type Void :=
  (LET mc_in_range1 <- #mc_i_v < #mc_src1_count_v;
    LET mc_in_range2 <- #mc_j_v < #mc_src2_count_v;
    LET mc_read_idx : Bit CouplingPairIdxSz <- IF #mc_in_range1 then (#mc_src1_base_v + UniBit (Trunc CouplingPairIdxSz 1) #mc_i_v) else (#mc_src2_base_v + UniBit (Trunc CouplingPairIdxSz 1) #mc_j_v);
    LET mc_copy_src : Bit WordSz <- #coupling_pair_src_table_v@[#mc_read_idx];
    LET mc_copy_dst : Bit WordSz <- #coupling_pair_dst_table_v@[#mc_read_idx];
    LET mc_j_next : Bit CouplingPairCountSz <- #mc_j_v + $1;
    LET mc_done <- !#mc_in_range1 && !#mc_in_range2;
    LET mc_full <- #mc_write_ptr_v == $$(natToWord DescTableNextIdSz 16);
    LET mc_blocked <- #mc_done || #mc_full;
    LET mc_overflow <- !#mc_done && #mc_full;
    Write "err" <- #mc_err_v || #mc_overflow;
    Write "error_code" <- IF #mc_overflow then $$(ERR_COUPLING_INVALID) else #mc_error_v;
    Write "coupling_pair_src_table" <- IF #mc_blocked then #coupling_pair_src_table_v else #coupling_pair_src_table_v@[UniBit (Trunc CouplingPairIdxSz 1) #mc_write_ptr_v <- #mc_copy_src];
    Write "coupling_pair_dst_table" <- IF #mc_blocked then #coupling_pair_dst_table_v else #coupling_pair_dst_table_v@[UniBit (Trunc CouplingPairIdxSz 1) #mc_write_ptr_v <- #mc_copy_dst];
    Write "coupling_pair_valid_table" <- IF #mc_blocked then #coupling_pair_valid_table_v else #coupling_pair_valid_table_v@[UniBit (Trunc CouplingPairIdxSz 1) #mc_write_ptr_v <- $$true];
    Write "mc_i" <- IF #mc_in_range1 then (#mc_i_v + $1) else #mc_i_v;
    Write "mc_j" <- IF #mc_in_range1 then #mc_j_v else #mc_j_next;
    Write "mc_write_ptr" <- IF #mc_blocked then #mc_write_ptr_v else (#mc_write_ptr_v + $1);
    Write "mc_phase" <- IF #mc_overflow then $$(natToWord 4 0) else (IF #mc_done then $$(WO~0~1~0~1) else $$(WO~0~1~0~0));
    Retv)%kami_action.

