Definition mcjoin_decoded (mc_phase_v : type (Bit 4)) (mc_i_v : type (Bit CouplingPairCountSz)) (mc_j_v : type (Bit CouplingPairCountSz)) (mc_src1_base_v : type (Bit CouplingPairIdxSz)) (mc_src1_count_v : type (Bit CouplingPairCountSz)) (mc_src2_base_v : type (Bit CouplingPairIdxSz)) (mc_src2_count_v : type (Bit CouplingPairCountSz)) (mc_write_ptr_v : type (Bit DescTableNextIdSz)) (coupling_pair_src_table_v : type (Vector (Bit WordSz) CouplingPairIdxSz)) (coupling_pair_dst_table_v : type (Vector (Bit WordSz) CouplingPairIdxSz)) (coupling_pair_valid_table_v : type (Vector Bool CouplingPairIdxSz)) (mc_err_v : type (Bool)) (mc_error_v : type (Bit WordSz)) : ActionT type Void :=
  (LET mc_empty <- (#mc_src1_count_v == $0) || (#mc_src2_count_v == $0);
    LET mc_idx1 : Bit CouplingPairIdxSz <- #mc_src1_base_v + UniBit (Trunc CouplingPairIdxSz 1) #mc_i_v;
    LET mc_idx2 : Bit CouplingPairIdxSz <- #mc_src2_base_v + UniBit (Trunc CouplingPairIdxSz 1) #mc_j_v;
