Definition lscan_decoded (lassert_phase_v : type (Bit 3)) (mem_v : type (Vector (Bit WordSz) MemAddrSz)) (mu_v : type (Bit WordSz)) (pc_v : type (Bit WordSz)) (trap_vector_v : type (Bit WordSz)) (err_v : type (Bool)) (error_code_v : type (Bit WordSz)) (lassert_cbase_v : type (Bit WordSz)) (lassert_flen_v : type (Bit WordSz)) (lassert_clen_v : type (Bit WordSz)) (lassert_nvars_v : type (Bit WordSz)) (lassert_fptr_v : type (Bit WordSz)) (lassert_cptr_v : type (Bit WordSz)) (lassert_clause_sat_v : type (Bool)) (lassert_counter_clause_sat_v : type (Bool)) (lassert_counter_seen_fail_v : type (Bool)) : ActionT type Void :=
  (LET fptr_a : Bit MemAddrSz <- UniBit (Trunc MemAddrSz _) #lassert_fptr_v;
    LET literal : Bit WordSz <- read_mem #fptr_a #mem_v;
    LET lit_sign : Bit 1 <- UniBit (ConstExtract 31 1 0) #literal;
    LET lit_is_zero <- #literal == $0;
    LET lit_is_neg <- (#lit_sign == $$(WO~1)) && !#lit_is_zero;
    LET lit_abs : Bit WordSz <- IF #lit_is_neg then ($0 - #literal) else #literal;
    LET caddr : Bit MemAddrSz <- UniBit (Trunc MemAddrSz _) (#lassert_cbase_v + #lit_abs);
    LET counter_caddr : Bit MemAddrSz <- UniBit (Trunc MemAddrSz _) (#lassert_cbase_v + #lassert_nvars_v + #lit_abs);
    LET asgn_word : Bit WordSz <- read_mem #caddr #mem_v;
    LET counter_asgn_word : Bit WordSz <- read_mem #counter_caddr #mem_v;
    LET asgn_t <- #asgn_word != $0;
    LET counter_asgn_t <- #counter_asgn_word != $0;
    LET lit_sat <- !#lit_is_zero && (IF #lit_is_neg then !#asgn_t else #asgn_t);
    LET counter_lit_sat <- !#lit_is_zero && (IF #lit_is_neg then !#counter_asgn_t else #counter_asgn_t);
    LET end_of_clause <- #lit_is_zero;
    LET last_clause <- #lassert_clen_v <= $1;
    LET model_clause_fail <- #end_of_clause && !#lassert_clause_sat_v;
    LET counter_clause_fail <- #end_of_clause && !#lassert_counter_clause_sat_v;
    LET counter_seen_fail_next <- #lassert_counter_seen_fail_v || #counter_clause_fail;
    LET final_counter_fail <- #end_of_clause && #lassert_clause_sat_v && #last_clause && !#counter_seen_fail_next;
    LET clause_fail <- #model_clause_fail || #final_counter_fail;
    LET all_done <- #end_of_clause && #lassert_clause_sat_v && #last_clause && #counter_seen_fail_next;
    LET clause_ok_cont <- #end_of_clause && #lassert_clause_sat_v && !#last_clause;
    LET cost_v : Bit WordSz <- #lassert_cptr_v;
    LET flen_x8 : Bit WordSz <- BinBit (Sll _ _) #lassert_flen_v ($$(WO~0~0~0~0~1~1));
    LET mu_success : Bit WordSz <- #mu_v + #flen_x8 + #cost_v + $1;
    LET mu_fail : Bit WordSz <- #mu_v + #flen_x8 + #cost_v + $1;
    LET next_phase : Bit 3 <- IF (#all_done || #clause_fail) then $$(WO~0~0~0) else $$(WO~0~1~0);
    LET next_clen : Bit WordSz <- IF #clause_ok_cont then (#lassert_clen_v - $1) else #lassert_clen_v;
    LET next_fptr : Bit WordSz <- #lassert_fptr_v + $1;
    LET next_clause_sat <- IF #end_of_clause then $$false else (IF #lit_sat then $$true else #lassert_clause_sat_v);
    LET next_counter_clause_sat <- IF #end_of_clause then $$false else (IF #counter_lit_sat then $$true else #lassert_counter_clause_sat_v);
    LET next_counter_seen_fail <- #counter_seen_fail_next;
    LET new_pc : Bit WordSz <- IF #all_done then (#pc_v + $1) else (IF #clause_fail then #trap_vector_v else #pc_v);
    LET new_mu : Bit WordSz <- IF #all_done then #mu_success else (IF #clause_fail then #mu_fail else #mu_v);
    LET new_err <- IF #clause_fail then $$true else #err_v;
    LET new_error_code_fsm : Bit WordSz <- IF #clause_fail then $$(ERR_LOGIC_VAL) else #error_code_v;
    Write "lassert_phase" <- #next_phase;
    Write "lassert_clen" <- #next_clen;
    Write "lassert_fptr" <- #next_fptr;
    Write "lassert_clause_sat" <- #next_clause_sat;
    Write "lassert_counter_clause_sat" <- #next_counter_clause_sat;
    Write "lassert_counter_seen_fail" <- #next_counter_seen_fail;
    Write "pc" <- #new_pc;
    Write "mu" <- #new_mu;
    Write "err" <- #new_err;
    Write "error_code" <- #new_error_code_fsm;
    Retv)%kami_action.

