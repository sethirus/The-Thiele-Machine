Definition mccommit_decoded (mc_phase_v : type (Bit 4)) (mc_write_base_v : type (Bit DescTableNextIdSz)) (mc_write_ptr_v : type (Bit DescTableNextIdSz)) (coupling_desc_next_id_v : type (Bit DescTableNextIdSz)) (coupling_desc_base_table_v : type (Vector (Bit CouplingPairIdxSz) CouplingDescIdxSz)) (coupling_desc_count_table_v : type (Vector (Bit CouplingPairCountSz) CouplingDescIdxSz)) (coupling_desc_valid_table_v : type (Vector Bool CouplingDescIdxSz)) : ActionT type Void :=
  (LET mc_desc_id : Bit CouplingDescIdxSz <- UniBit (Trunc CouplingDescIdxSz 1) #coupling_desc_next_id_v;
    LET mc_final_count : Bit CouplingPairCountSz <- #mc_write_ptr_v - #mc_write_base_v;
    Write "coupling_desc_base_table" <- #coupling_desc_base_table_v@[#mc_desc_id <- UniBit (Trunc CouplingPairIdxSz 1) #mc_write_base_v];
    Write "coupling_desc_count_table" <- #coupling_desc_count_table_v@[#mc_desc_id <- #mc_final_count];
    Write "coupling_desc_valid_table" <- #coupling_desc_valid_table_v@[#mc_desc_id <- $$true];
    Write "coupling_desc_next_id" <- #coupling_desc_next_id_v + $1;
    Write "coupling_pair_next_id" <- #mc_write_ptr_v;
    Write "mc_phase" <- $$(natToWord 4 0);
    Retv)%kami_action.

