Definition Retire (b : HWB) (i : vm_instruction) (d : HWB) : Prop :=
  hw_live b /\ (exists n, Busy_runs (step_next b) d n) /\ hw_idle d /\
  hwb_snapshot d = kami_step (hwb_snapshot b) i.

Theorem retire_runner : forall b i d, Retire b i d ->
  exists k, fst (run_boundary_rules k b) = d.
Proof.
  intros b i d [Hl [[n Hn] _]]. exists (S n).
  apply runs_runner_exact.
  exact (runs_fire b "step" (step_next b) d n (live_step_selected b Hl) (busy_runs_runs _ _ _ Hn)).
Qed.

Theorem retire_unique : forall b i j d d', Retire b i d -> Retire b j d' -> d = d'.
Proof.
  intros b i j d d' [_ [[n Hn] [Hd _]]] [_ [[n' Hn'] [Hd' _]]].
  exact (proj1 (busy_runs_unique _ _ _ Hn Hd _ _ Hn' Hd')).
Qed.

Theorem retire_multistep : forall b i d, Retire b i d ->
  exists l, Multistep thieleCore (hwb_regs b) (hwb_regs d) l.
Proof.
  intros b i d H. destruct (retire_runner b i d H) as [k Hk].
  exists (snd (run_boundary_rules k b)). rewrite <- Hk. apply run_boundary_rules_actual.
Qed.

Lemma step_idle : forall b, hw_lassert_phase (step_next b) = natToWord 3 0 ->
  hw_chsh_phase (step_next b) = natToWord 5 0 -> hw_mc_phase (step_next b) = natToWord 4 0 ->
  hw_idle (step_next b).
Proof. intros b H1 H2 H3. exact (conj H1 (conj H2 H3)). Qed.

