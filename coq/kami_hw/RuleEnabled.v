(** The step rule's evaluation is gated by exactly its five guards. *)
Definition step_guards (b : HWB) : bool :=
  andb (negb (hw_halted b)) (andb (negb (hw_err b))
    (andb (if weq (hw_lassert_phase b) (natToWord 3 0) then true else false)
      (andb (if weq (hw_mc_phase b) (natToWord 4 0) then true else false)
        (if weq (hw_chsh_phase b) (natToWord 5 0) then true else false)))).

