(** * Guard prefixes *)

Lemma eval_read_some : forall k old r kind (cont : fullType type kind -> ActionT type k) v,
  action_read old r kind = Some v ->
  eval_linear_action old (ReadReg r kind cont) = eval_linear_action old (cont v).
Proof. intros. cbn [eval_linear_action]. rewrite H. reflexivity. Qed.

Lemma eval_assert_false : forall k (old : RegsT) (p : Expr type (SyntaxKind Bool)) (cont : ActionT type k),
  evalExpr p = false -> eval_linear_action old (Assert_ p cont) = None.
Proof. intros. cbn [eval_linear_action]. rewrite H. reflexivity. Qed.

Lemma eval_assert_true : forall k (old : RegsT) (p : Expr type (SyntaxKind Bool)) (cont : ActionT type k),
  evalExpr p = true -> eval_linear_action old (Assert_ p cont) = eval_linear_action old cont.
Proof. intros. cbn [eval_linear_action]. rewrite H. reflexivity. Qed.

(** A rule that opens by reading one register and asserting a guard on it is
    disabled when the guard evaluates to false. The head shape is obtained by
    unification, so the rule body is never reduced. *)
Lemma rule_disabled_of_head : forall (r : cpu_rule) old name kind v
    (guard : fullType type kind -> Expr type (SyntaxKind Bool))
    (cont : fullType type kind -> ActionT type Void),
  attrType r type = ReadReg name kind (fun x => Assert_ (guard x) (cont x)) ->
  action_read old name kind = Some v ->
  evalExpr (guard v) = false ->
  eval_cpu_rule old r = None.
Proof.
  intros r old name kind v guard cont Hr Hv Hg. unfold eval_cpu_rule. rewrite Hr.
  rewrite (eval_read_some _ _ _ _ _ _ Hv). rewrite eval_assert_false by exact Hg. reflexivity.
Qed.

