(** * Write-only actions with distinct register names evaluate *)

(** [seen] holds the names written earlier in the action. The name check is
    a computed [if] rather than a conjunction, so a proof over a long action
    carries no copies of the remaining action in its terms. *)
Fixpoint total_from {k} (seen : list string) (a : ActionT type k) : Prop :=
  match a with
  | Let_ _ cont => forall v, total_from seen (cont v)
  | WriteReg r _ cont => if existsb (String.eqb r) seen then False else total_from (r :: seen) cont
  | Displ _ cont => total_from seen cont
  | Return _ => True
  | _ => False
  end.

Lemma existsb_eqb_false : forall r seen r',
  existsb (String.eqb r) seen = false -> In r' seen -> r <> r'.
Proof.
  intros r seen r' H Hin E. subst r'.
  assert (T : existsb (String.eqb r) seen = true).
  { apply existsb_exists. exists r. split; [exact Hin|apply String.eqb_refl]. }
  congruence.
Qed.

Theorem total_from_eval : forall k (a : ActionT type k) seen old,
  total_from seen a ->
  exists u ret, eval_linear_action old a = Some (u, ret) /\
    forall r, In r seen -> M.find r u = None.
Proof.
  intros k a. induction a; intros seen old Ht; cbn [total_from] in Ht; try contradiction.
  - destruct (H (evalExpr e) seen old (Ht _)) as [u [ret [He Hn]]].
    exists u, ret. cbn [eval_linear_action]. split; assumption.
  - destruct (existsb (String.eqb r) seen) eqn:Hr; [contradiction|rename Ht into Hc].
    destruct (IHa (r :: seen) old Hc) as [u [ret [He Hn]]].
    exists (M.add r (existT _ _ (evalExpr e)) u), ret. cbn [eval_linear_action].
    rewrite He, (Hn r (or_introl eq_refl)). split; [reflexivity|].
    intros r' Hin. rewrite M.find_add_2.
    + apply Hn. right. exact Hin.
    + intro E. subst r'. exact (existsb_eqb_false r seen r Hr Hin eq_refl).
  - destruct (IHa seen old Ht) as [u [ret [He Hn]]].
    exists u, ret. cbn [eval_linear_action]. split; assumption.
  - exists (M.empty _), (evalExpr e). cbn [eval_linear_action].
    split; [reflexivity|]. intros. apply M.find_empty.
Qed.

