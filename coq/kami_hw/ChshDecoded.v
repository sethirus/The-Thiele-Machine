Definition chsh_next (b : HWB) : HWB :=
  hwb_after b (fun key => observe_action_write (M.empty _) key (hwb_chsh_decoded b)).

Lemma chsh_rule_next : forall b, rule_next chsh_rule b = chsh_next b.
Proof.
  intro b. unfold rule_next, chsh_next. apply hwb_after_ext. intro key. apply chsh_observer.
Qed.

Theorem chsh_rule_enabled : forall b,
  hw_chsh_phase b <> natToWord 5 0 ->
  exists u, eval_cpu_rule (hwb_regs b) chsh_rule = Some u /\
    M.union u (hwb_regs b) = hwb_regs (chsh_next b).
Proof.
  intros b Hp.
  assert (He : exists u, eval_cpu_rule (hwb_regs b) chsh_rule = Some u).
  { unfold eval_cpu_rule. rewrite chsh_rule_action. unfold chsh_fetch_action.
    repeat first [progress cbn [eval_linear_action evalExpr evalUniBool evalConstT]
    | rewrite hwb_read_chsh_phase
