  | rewrite hwb_read_chsh_sign01
  | rewrite hwb_read_chsh_sign10
  | rewrite hwb_read_chsh_sign11
  | rewrite hwb_read_chsh_n00sq
  | rewrite hwb_read_chsh_n01sq
  | rewrite hwb_read_chsh_n10sq
  | rewrite hwb_read_chsh_n11sq
  | rewrite hwb_read_chsh_d00sq
  | rewrite hwb_read_chsh_d01sq
