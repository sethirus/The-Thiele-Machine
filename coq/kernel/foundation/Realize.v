(** Realize.v: the entry points of the extracted machines, and the proof that
    they are the functions the theorems are about.

    The small machine (minimal/EarnedCore.v), the multi-register host with
    and without PAY (minimal/EarnedMulti.v, minimal/EarnedMultiPriced.v), the
    fixed host program U (UniversalLayout.v) with its loader (UniversalSim.v)
    and the host property PSlot (UniversalCodes.v) are extracted to OCaml
    from RealizeExtract.v. The only things extracted are the names defined
    in this file and in RealizePriced.v, all prefixed rlz_. This file shows
    that each of them is, by conversion (Coq's own equality check, eq_refl),
    the object that the theorems speak of.

    How the names are made.
      * Where the original function lives in a file that Coq's extraction can
        use (EarnedCore.v, EarnedMulti.v, EarnedMultiPriced.v), the rlz_ name
        is a Definition equal to the original at the original arguments.
      * Coq's monolithic extraction refuses any constant that lives in a file
        containing a module alias, and any term that names a constant through
        a module alias. UniversalCodes.v is such a file. For its functions
        (the pairing, the codes of instructions, the property PSlot) and for
        the loader hregs the rlz_ name is a copy written out with canonical
        names, followed by an eq_refl proof that it is the original, so Coq's
        kernel checks each copy.
      * The program U is a list of thousands of instructions, built in files
        Coq's extraction cannot read. RealizePrograms.v holds U as a literal
        list, generated by scripts/realize_gen_programs.py from Coq's own
        evaluation of U, with an eq_refl proof that it is U.

    The statements rlz_small_halting_correspondence,
    rlz_small_mu_conservation_trace and rlz_host_halting_statement restate
    theorems or definitions of the originals with the rlz_ names, and are
    proved by the originals themselves.

    Dependencies: the Coq standard library, the files named above. No axioms,
    no Admitted.                                                           *)

(* SCOPE NOTE: foundation connectivity gap suppressed, on purpose: this
   file only renames and re-proves; the claims about these machines are in
   the files named above. *)

