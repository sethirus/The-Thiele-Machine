Theorem rlz_small_halting_correspondence : forall M a b,
  (exists n, E.mstep M (E.mrun n M (1, (a, b))) = None) <->
  (exists n, E.halted (rlz_small_compile M)
               (E.core_of (rlz_small_run_prog n (rlz_small_compile M) (rlz_small_start a b)))).
Proof. exact E.halting_correspondence. Qed.

