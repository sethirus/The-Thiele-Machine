(* Copies of the functions of UniversalCodes.v that the host and its loader
   use, written with canonical names so that extraction can read them. Each
   is followed by the eq_refl proof that it is the original. *)

Definition rlz_pair (m n : nat) : nat := (n + n + 1) * 2 ^ m.

Fixpoint rlz_unp (fuel x m : nat) : option (nat * nat) :=
  match fuel with
  | 0 => None
  | S f =>
      match x with
      | 0 => None
      | S _ => if Nat.odd x then Some (m, Nat.div2 x) else rlz_unp f (Nat.div2 x) (S m)
      end
  end.

Definition rlz_unpair (x : nat) : option (nat * nat) := rlz_unp x x 0.

Definition rlz_pcode (p : Minimal.EarnedCore.prop) : nat :=
  match p with
  | Minimal.EarnedCore.PZero => 0
  | Minimal.EarnedCore.PEven => 1
  | Minimal.EarnedCore.PGe n => n + 2
  end.

Definition rlz_pdec (n : nat) : Minimal.EarnedCore.prop :=
  match n with
  | 0 => Minimal.EarnedCore.PZero
  | 1 => Minimal.EarnedCore.PEven
  | S (S m) => Minimal.EarnedCore.PGe m
  end.

Definition rlz_ccode (c : Minimal.EarnedCore.ctr) : nat :=
  match c with Minimal.EarnedCore.CA => 0 | Minimal.EarnedCore.CB => 1 end.

Definition rlz_icode (i : Minimal.EarnedCore.instr) : nat :=
  match i with
  | Minimal.EarnedCore.INC c => rlz_pair 0 (rlz_ccode c)
  | Minimal.EarnedCore.DEC c j => rlz_pair 1 (rlz_pair (rlz_ccode c) j)
  | Minimal.EarnedCore.HALT => rlz_pair 2 0
  | Minimal.EarnedCore.CHECK p c => rlz_pair 3 (rlz_pair (rlz_ccode c) (rlz_pcode p))
  | Minimal.EarnedCore.COMMIT p c => rlz_pair 4 (rlz_pair (rlz_ccode c) (rlz_pcode p))
  | Minimal.EarnedCore.CERTIFY => rlz_pair 5 0
  end.

Definition rlz_prog_code (P : list Minimal.EarnedCore.instr) : nat :=
  Minimal.EarnedGeneric.encode (map rlz_icode P).

Lemma rlz_pair_is : rlz_pair = UC.pair. Proof. reflexivity. Qed.
Lemma rlz_unp_is : rlz_unp = UC.unp. Proof. reflexivity. Qed.
Lemma rlz_unpair_is : rlz_unpair = UC.unpair. Proof. reflexivity. Qed.
Lemma rlz_pcode_is : rlz_pcode = UC.pcode. Proof. reflexivity. Qed.
Lemma rlz_pdec_is : rlz_pdec = UC.pdec. Proof. reflexivity. Qed.
Lemma rlz_ccode_is : rlz_ccode = UC.ccode. Proof. reflexivity. Qed.
Lemma rlz_icode_is : rlz_icode = UC.icode. Proof. reflexivity. Qed.
Lemma rlz_prog_code_is : rlz_prog_code = UC.prog_code. Proof. reflexivity. Qed.

(* The property language of the host (UniversalCodes.v): the one property
   PSlot, which holds of a counter holding pair (pcode p) v with p true of
   v. *)
Definition rlz_host_prop_eqb (p q : Minimal.UniversalCodes.hprop) : bool :=
  match p, q with Minimal.UniversalCodes.PSlot, Minimal.UniversalCodes.PSlot => true end.

Definition rlz_host_eval (p : Minimal.UniversalCodes.hprop) (x : nat) : bool :=
  match rlz_unpair x with
  | Some (m, v) => Minimal.EarnedCore.eval (rlz_pdec m) v
  | None => false
  end.

Lemma rlz_host_prop_eqb_is : rlz_host_prop_eqb = UC.hprop_eqb. Proof. reflexivity. Qed.
Lemma rlz_host_eval_is : rlz_host_eval = UC.heval. Proof. reflexivity. Qed.

Definition rlz_host_exec :=
  Minimal.EarnedMulti.exec rlz_host_prop_eqb rlz_host_eval.
Definition rlz_host_run :=
  Minimal.EarnedMulti.run rlz_host_prop_eqb rlz_host_eval.
Definition rlz_host_step :=
  Minimal.EarnedMulti.step rlz_host_prop_eqb rlz_host_eval.
Definition rlz_host_run_prog :=
  Minimal.EarnedMulti.run_prog rlz_host_prop_eqb rlz_host_eval.
Definition rlz_host_trace_of :=
  Minimal.EarnedMulti.trace_of rlz_host_prop_eqb rlz_host_eval.
Definition rlz_host_start := @Minimal.EarnedMulti.start Minimal.UniversalCodes.hprop.

(* The program U: the literal list of RealizePrograms.v, proved equal to U. *)
Definition rlz_host_program :
  list (@Minimal.EarnedMulti.instr Minimal.UniversalCodes.hprop) :=
  Kernel.RealizePrograms.rlz_host_program.

Lemma rlz_host_program_is : rlz_host_program = UL.U.
Proof. exact Kernel.RealizePrograms.rlz_host_program_is. Qed.

(* The loader: RA and RB hold the guest's inputs, PROG the program code,
   GPC the guest pc 1; every other register 0 (UniversalSim.v hregs, hload). *)
Definition rlz_host_regs (P : list Minimal.EarnedCore.instr) (x y r : nat) : nat :=
  if Nat.eqb r 0 then x else
  if Nat.eqb r 1 then y else
  if Nat.eqb r 2 then rlz_prog_code P else
  if Nat.eqb r 3 then 1 else 0.

Definition rlz_host_load (P : list Minimal.EarnedCore.instr) (x y : nat)
  : @Minimal.EarnedMulti.state Minimal.UniversalCodes.hprop :=
  rlz_host_start (rlz_host_regs P x y).

Lemma rlz_host_regs_is : rlz_host_regs = US.hregs. Proof. reflexivity. Qed.
Lemma rlz_host_load_is : rlz_host_load = US.hload. Proof. reflexivity. Qed.

(* The extracted host run is the run of the theorems. *)
Lemma rlz_host_run_prog_is :
  rlz_host_run_prog = M.run_prog UC.hprop_eqb UC.heval.
Proof. reflexivity. Qed.

(* The host after n steps of U from the loaded guest P, inputs x, y: the
   term the theorems of UniversalRun.v call hrun P x y n. *)
Definition rlz_host_at (P : list Minimal.EarnedCore.instr) (x y n : nat)
  : @Minimal.EarnedMulti.state Minimal.UniversalCodes.hprop :=
  rlz_host_run_prog n rlz_host_program (rlz_host_load P x y).

Lemma rlz_host_at_is : forall P x y n,
  rlz_host_at P x y n = M.run_prog UC.hprop_eqb UC.heval n UL.U (US.hload P x y).
Proof. intros. unfold rlz_host_at. rewrite rlz_host_program_is. reflexivity. Qed.

(* The guest the host simulates: the small machine after m steps from
   start x y. *)
Definition rlz_guest_at (P : list Minimal.EarnedCore.instr) (x y m : nat)
  : Minimal.EarnedCore.state :=
  rlz_small_run_prog m P (rlz_small_start x y).

(* The statement of UniversalRun.v universal_halting, with the extracted
   names: the guest halts exactly when the host halts. *)
Definition rlz_host_halting_statement (P : list E.instr) (x y : nat) : Prop :=
  (exists m, E.halted P (E.core_of (rlz_guest_at P x y m))) <->
  (exists n, M.halted UL.U (M.core_of (rlz_host_at P x y n))).
