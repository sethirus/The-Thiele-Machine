  E.mu (rlz_small_run tr s) = E.mu s + E.total_cost tr.
Proof. exact E.mu_conservation_trace. Qed.

Theorem rlz_small_run_prog_trace : forall n P s,
  rlz_small_run_prog n P s = rlz_small_run (rlz_small_trace_of n P s) s.
Proof. exact E.run_prog_trace. Qed.

