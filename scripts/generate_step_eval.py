#!/usr/bin/env python3
"""Generate StepEval.v: evaluation tactics for the decoded step rule.

The generated module defines canonical ISA-v2 format-0 instruction words with
symbolic operand bits, a reduction tactic that keeps word arithmetic and all
typed-boundary projections folded, and one preservation lemma for every
register the step rule never writes.
"""
import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
from generate_rule_next import fields  # noqa: E402

SOURCE = ROOT / 'coq/kami_hw/ThieleCPUCore.v'
TARGET = ROOT / 'coq/kami_hw/StepEval.v'

HEADER = '''(** StepEval.v: generated by scripts/generate_step_eval.py.
    Canonical ISA-v2 format-0 words with symbolic operand bits, the reduction
    tactic used for per-opcode field equations of [step_next], and
    preservation of every register the step rule never writes. *)
Require Import Kami.Kami Kami.Semantics.
From Coq Require Import String NArith Eqdep_dec Arith.PeanoNat.
From KamiHW Require Import ThieleTypes ThieleCPUCore HWBoundary RuleNext RuleStep
  BoundaryDecoded ActionObservation DispatchObservation.
Open Scope string_scope.

Definition bits4 (x0 x1 x2 x3 : bool) : word 4 :=
  WS x0 (WS x1 (WS x2 (WS x3 WO))).
Definition bits8 (x0 x1 x2 x3 x4 x5 x6 x7 : bool) : word 8 :=
  WS x0 (WS x1 (WS x2 (WS x3 (WS x4 (WS x5 (WS x6 (WS x7 WO))))))).

(** Version 2, format 0, zero flags and extension words; low lane
    opcode [31:24], A [23:16], B [15:8], cost [7:0]. *)
Definition legacy_word (op a b c : word 8) : word InstrSz :=
  combine c (combine b (combine a (combine op (NToWord 96 (N.shiftl 2 88))))).

'''


def written_keys():
    s = SOURCE.read_text()
    body = s[s.index('Definition dispatch_decoded'):s.index('Definition thieleCore')]
    body = re.sub(r'\(\*.*?\*\)', '', body, flags=re.S)
    return re.findall(r'Write\s+"(\w+)"', body)


def blacklist():
    projs = ' '.join(f'hw_{n}' for n, _ in fields())
    return ('wplus wminus wmult wand wor wxor wnot wlshift wrshift wordToNat wordToN wlt_dec '
            f'hwb_bianchi hwb_tensor_total {projs}')


def generate():
    fs = fields()
    written = set(written_keys())
    projs = ' '.join(f'hw_{n}' for n, _ in fs)
    t = HEADER
    t += f'Ltac hw_lazy := lazy -[{blacklist()}].\n\n'
    t += """(** Close a field equation after reduction: either both sides are
    syntactically equal, or a stuck condition outside binders is split (bit
    variables first) and both branches are reduced again. *)
Ltac hw_split_step :=
  first
    [ match goal with |- context [if ?t then _ else _] => is_var t; destruct t end
    | match goal with
      | |- context [if ?t then _ else _] =>
          lazymatch t with
          | (if _ then _ else _) => fail
          | _ => destruct t
          end
      end ].

Ltac hw_split_close :=
  lazymatch goal with
  | |- ?x = ?x => reflexivity
  | _ => tryif hw_split_step then (hw_lazy; hw_split_close)
         else fail 1 "field equation is not syntactic after splitting"
  end.

(** Prove [hw_field (step_next b) = rhs] for a fixed fetched word: reduce the
    decoded action, clear proof-carrying zero-extension casts, reduce again,
    then close by syntactic comparison with case splits. Hypotheses
    [hwb_bianchi b = _] are substituted first. *)
Ltac hw_field :=
  intros;
  match goal with H : step_fetched _ = _ |- _ => rewrite (step_next_fetched _ _ H) end;
"""
    t += f'  cbn [hwb_after {projs}];\n'
    t += """  unfold hwb_decoded;
  repeat match goal with H : hwb_bianchi _ = _ |- _ => rewrite H end;
  hw_lazy; clear_concrete_word_casts; hw_lazy; hw_split_close.

"""
    for n, _ in fs:
        if n in written:
            continue
        t += f'Lemma step_keeps_{n} : forall b, hw_{n} (step_next b) = hw_{n} b.\n'
        t += f'Proof. intro b. unfold step_next. cbn [hwb_after hw_{n}]. unfold hwb_decoded. hw_lazy. reflexivity. Qed.\n'
    return t, len(fs) - len(written)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated, count = generate()
    if args.check:
        if TARGET.read_text() != generated:
            raise SystemExit('StepEval.v is stale; regenerate it')
    else:
        TARGET.write_text(generated)
    print(f'StepEval: {count} preserved registers')
