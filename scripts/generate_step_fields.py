def inline(expr):
    import re
    return re.sub(r'\b(AL|AH|BL|BH|Bw|A|C)\b', lambda m: NAMES[m.group(1)], expr)


def generate(only=None):
    t = HEADER
    count = 0
    for name, spec in OPS.items():
        if only and name not in only:
            continue
        low = name.lower()
        t += (f'Definition {low}_word ({BITS} : bool) : word InstrSz :=\n'
              f'  legacy_word OP_{name} {inline("A")} {inline("Bw")} {inline("C")}.\n')
        for f in FIELDS:
            rhs = inline(spec.get(f, default(f)))
            t += (f'Lemma step_{low}_{f} : forall {BITS} b,\n'
                  f'  step_fetched b = {low}_word {BITS} -> hwb_bianchi b = false ->\n'
                  f'  hw_{f} (step_next b) = {rhs}.\n'
                  'Proof. hw_field. Qed.\n')
            count += 1
        t += '\n'
    return t, count


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--only', nargs='*')
    parser.add_argument('--out')
    args = parser.parse_args()
    generated, count = generate(args.only)
    target = Path(args.out) if args.out else TARGET
    if args.check:
        if target.read_text() != generated:
            raise SystemExit('StepFields.v is stale; regenerate it')
    else:
        target.write_text(generated)
    print(f'StepFields: {count} field equations')
