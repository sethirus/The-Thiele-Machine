PC1 = 'wplus (hw_pc b) (natToWord WordSz 1)'
MU = 'wplus (hw_mu b) (zext C 24)'
MU1 = 'wplus (wplus (hw_mu b) (zext C 24)) (natToWord WordSz 1)'
