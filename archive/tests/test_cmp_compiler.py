@pytest.mark.parametrize("fuel", [1, 1000, 250000])
def test_non_halting_programs_use_all_their_fuel(exe, fuel):
    cases = []
    for n, p, nin, out in cc.nonhalting():
        cases.append(dict(id=n, prog=p, nin=nin, out=out, xs=[0] * nin, ifuel=fuel, hfuel=fuel))
    for c, r in zip(cases, run_cases(exe, cases)):
        assert r.wf and not r.halted, c["id"]
        assert r.steps == fuel, (c["id"], r.steps, fuel)      # cr_left = 0: every unit of fuel was a step
        assert 1 <= r.pc <= r.host_len                         # still inside the program
        assert not r.interp_ok                                 # the interpreter also runs out of fuel
        assert cs.interp(c["prog"], [0] * c["nin"], max_ops=fuel * 3) is None


def test_exact_fuel_boundary(exe):
    """A program that halts after exactly k host steps is not halted with
    fuel k - 1 and halted with fuel k and every larger fuel."""
    _, prog, nin, out, ref = cc.e_mul_loop()
    xs = [9, 13]
    res, py = full_check(exe, "mul_boundary", prog, nin, out, xs, ref=ref)
    k = res.steps
    assert k > 100
    cases = [dict(id="f%d" % f, prog=prog, nin=nin, out=out, xs=xs, ifuel=10**6, hfuel=f) for f in (k - 1, k, k + 1, 2 * k)]
    r = run_cases(exe, cases)
    assert not r[0].halted and r[0].steps == k - 1
    for x in r[1:]:
        assert x.halted and x.answer == 117
    assert r[1].steps == k and r[2].steps == k and r[3].steps == k
    # fuel k - 1 left the program one step short of its end: still inside it
    assert 1 <= r[0].pc <= r[0].host_len


def test_unhalted_state_is_a_prefix_of_the_run(exe):
    """With fuel f < k the runner stops in a state the python host machine
    reaches after exactly f steps (pc and registers)."""
    _, prog, nin, out, ref = cc.e_gcd()
    xs = [48, 18]
    res, _ = full_check(exe, "gcd_prefix", prog, nin, out, xs, ref=ref)
    k = res.steps
    blocks = ch.run_driver(exe, cs.dump_text(nin, out, prog))
    mm, host = cs.parse_dump("\n".join(blocks[0] + ["END"]))
    regs = cs.load_regs(xs, res.nvf)
    for f in (0, 1, 7, k // 3, k // 2, k - 1):
        r = run_cases(exe, [dict(id="p", prog=prog, nin=nin, out=out, xs=xs, ifuel=10**6, hfuel=f)])[0]
        h, steps, pc, rg = cs.run_host(host, regs, f)
        assert (h, steps) == (False, f)
        assert r.pc == pc and not r.halted
        assert r.vars == [rg.get(x + 1, 0) for x in range(r.nv0)]


