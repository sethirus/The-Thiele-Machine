"""Stress and differential tests of the verified compiler, run on the code
EXTRACTED from the Coq definitions (ocaml/CmpExtract.v, ocaml/cmp_driver.ml).

What is compared, for every program and input:

  A  the answer against ordinary mathematics (math.gcd, factorial, a plain
     ackermann, sorted(), a python simulation of the tiny machine ...)
  B  the extracted source interpreter (CmpLang.v cmp_interp): operation count
     and every variable, against an independent python interpreter written
     from the semantics (tests/cmp_src.py)
  C  the extracted runner of the compiled host program (CmpRun.v cmp_exec):
     every variable (registers 1 .. nv0) and the answer, against B
  D  the dumped counter machine program and host program, executed by python
     virtual machines (tests/cmp_src.py): the host machine's step count and
     registers equal those of the extracted runner, and the counter machine's
     registers equal the host's (one source program, two machines)
  E  coqc vm_compute of the Coq definitions themselves (shape check,
     interpreter, runner) on small cases
  F  bounded runs: a program that does not halt uses all its fuel and is
     reported unhalted; a program that halts after exactly k host steps is
     unhalted with fuel k - 1 and halted with fuel k (cmp_exec_complete,
     cmp_exec_unhalted)

Random programs (terminating, and with wild loops that may not terminate)
are generated by tests/cmp_corpus.py. Measured steps and times go to the
report file named by THIELE_CMP_REPORT, when set.

The compiler, the interpreter and the runner are never reimplemented here
for the comparison of C: they come out of the extraction; python only
supplies independent values to compare with.
"""

