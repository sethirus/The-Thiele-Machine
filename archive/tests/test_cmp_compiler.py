def _pack(digits):
    return sum(d * cc.BASE ** i for i, d in enumerate(digits))


def test_packed_list_sort(exe):
    name, prog, nin, out, ref = cc.e_sort5()
    rng = random.Random(20261005)
    cases = [[0], [_pack([3, 2, 1, 0, 3])], [_pack([0, 1, 2, 3, 0])], [1023]] + \
            [[rng.randrange(cc.BASE ** 5)] for _ in range(6)]
    for xs in cases:
        res, py = full_check(exe, name, prog, nin, out, xs, ref=ref)
        digits = []
        v = res.answer
        for _ in range(5):
            digits.append(v % cc.BASE)
            v //= cc.BASE
        assert digits == sorted(digits)


