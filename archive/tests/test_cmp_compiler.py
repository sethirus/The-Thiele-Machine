def interp_fuel(prog, ops):
    return 2 * ops + 2 * cs.size_nodes(prog) + 200


def run_cases(exe, cases):
    """cases: list of dicts id, prog, nin, out, xs, ifuel, hfuel. Returns
    parsed results in order."""
    text = "\n".join(cs.case_text(c["id"], c["nin"], c["out"], c["ifuel"], c["hfuel"], c["xs"], c["prog"]) for c in cases)
    blocks = ch.run_driver(exe, text)
    assert len(blocks) == len(cases)
    return [ch.Result(b) for b in blocks]


def run_one_adaptive(exe, cid, prog, nin, out, xs, ops, start=3_000_000, cap=10**9):
    """Run until the host halts (the theorems say it does once the fuel is
    enough) with a fuel growing tenfold from start. ops is the python
    operation count. Returns the Result."""
    hf = start
    while True:
        r = run_cases(exe, [dict(id=cid, prog=prog, nin=nin, out=out, xs=xs, ifuel=interp_fuel(prog, ops), hfuel=hf)])[0]
        if r.halted or hf >= cap:
            return r
        hf *= 10


def check_against_python(res, prog, nin, out, xs, py):
    """B and C: the extracted interpreter and runner against the python
    interpreter's result py = (env, ops)."""
    env, ops = py
    n0 = cs.nv0(prog, nin, out)
    want = [env.get(i, 0) for i in range(n0)]
    assert res.wf
    assert res.nv0 == n0
    assert res.interp_ok, "extracted interpreter gave up"
    assert res.interp_ops == ops, ("operation counts differ", res.interp_ops, ops)
    assert res.interp_vars == want, ("interpreter variables differ", res.interp_vars, want)
    assert res.halted, "the compiled program did not halt (fuel too small?)"
    assert res.vars == want, ("compiled program variables differ", res.vars, want)
    assert res.answer == env.get(out, 0)
    assert res.pc == 1 + res.host_len


def check_vms(exe, res, prog, nin, out, xs, label):
    """D: the dumped programs on the python machines."""
    if res.steps > VM_LIMIT:
        return None
    blocks = ch.run_driver(exe, cs.dump_text(nin, out, prog))
    mm, host = cs.parse_dump("\n".join(blocks[0] + ["END"]))
    assert len(mm) == res.mm_len and len(host) == res.host_len
    regs = cs.load_regs(xs, res.nvf)
    hh, hsteps, hpc, hregs = cs.run_host(host, regs, res.steps + 10)
    assert hh and hsteps == res.steps and hpc == res.pc, (label, hh, hsteps, res.steps)
    mh, msteps, mpc, mregs = cs.run_mm(mm, regs, res.steps + 10)
    assert mh and mpc == 1 + len(mm)
    for r in range(1, res.nvf + 1):
        assert hregs.get(r, 0) == mregs.get(r, 0), (label, "register", r)
    for x in range(res.nv0):
        assert hregs.get(x + 1, 0) == res.vars[x], (label, "variable", x)
    return msteps


def record(name, xs, res, ops, msteps):
    REPORT.append(dict(name=name, inputs=list(xs), source_ops=ops, mm_steps=msteps, host_steps=res.steps,
                       mm_len=res.mm_len, host_len=res.host_len, t_compile=res.t_compile, t_run=res.t_run))


def full_check(exe, name, prog, nin, out, xs, ref=None, vms=True, start=3_000_000):
    py = cs.interp(prog, xs, max_ops=5 * 10**7, max_value=10**12)
    assert py is not None, "python interpreter budget exceeded for %s%s" % (name, xs)
    res = run_one_adaptive(exe, name, prog, nin, out, xs, py[1], start=start)
    check_against_python(res, prog, nin, out, xs, py)
    if ref is not None:
        want = ref(*xs)
        got = py[0].get(out, 0)
        if isinstance(want, tuple):
            assert (py[0].get(out, 0), py[0].get(out + 1, 0)) == want, (name, xs)
        else:
            assert got == want, (name, xs, got, want)
    msteps = check_vms(exe, res, prog, nin, out, xs, "%s%s" % (name, xs)) if vms else None
    record(name, xs, res, py[1], msteps)
    return res, py


