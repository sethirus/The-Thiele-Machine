def _missing(why, config=None):
    """A missing toolchain fails the test, it does not skip it, whenever CI is set
    (every automated run sets it), under GitHub Actions, with --strict-backends and
    with THIELE_STRICT_BACKENDS, so a lost install cannot turn into a pass. Without
    those the test skips with the reason (THIELE_CMP_ALLOW_SKIP lets a CI run skip)."""
    on = {"1", "true", "yes", "on"}
    strict = (
        os.environ.get("CI", "").strip().lower() in on
        or bool(os.environ.get("GITHUB_ACTIONS"))
        or os.environ.get("THIELE_STRICT_BACKENDS", "0").strip().lower() in on
        or bool(config is not None and config.getoption("--strict-backends", default=False))
    )
    if strict and not os.environ.get("THIELE_CMP_ALLOW_SKIP"):
        pytest.fail(why)
    pytest.skip(why)


