def test_the_comparison_notices_a_corrupted_program(exe):
    _, prog, nin, out, ref = cc.e_gcd()
    xs = [24, 36]
    res, py = full_check(exe, "gcd", prog, nin, out, xs, ref=ref)
    blocks = ch.run_driver(exe, cs.dump_text(nin, out, prog))
    mm, host = cs.parse_dump("\n".join(blocks[0] + ["END"]))
    regs = cs.load_regs(xs, res.nvf)
    # flip one jump target of the host program: the run must differ
    changed = 0
    for i, ins in enumerate(host):
        if ins[0] == "dec" and ins[2] > 1:
            bad = list(host)
            bad[i] = ("dec", ins[1], ins[2] - 1)
            h, steps, pc, rg = cs.run_host(bad, regs, 20000)
            same = h and steps == res.steps and all(rg.get(x + 1, 0) == res.vars[x] for x in range(res.nv0))
            if not same:
                changed += 1
    assert changed >= 3
    # change one counter machine instruction: the machines disagree
    bad = list(mm)
    for i, ins in enumerate(bad):
        if ins[0] == "inc":
            bad[i] = ("inc", ins[1] + 1)
            break
    h, steps, pc, rg = cs.run_mm(bad, regs, 20000)
    assert not (h and all(rg.get(x + 1, 0) == res.vars[x] for x in range(res.nv0)))


