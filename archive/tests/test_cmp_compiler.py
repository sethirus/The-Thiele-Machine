def _fuzz_cases(rng, count, wild):
    out = []
    g = cc.Gen(rng, nvars=5, wild=wild)
    for i in range(count):
        nin = rng.randint(1, 4)
        prog = g.program(nin)
        xs = [rng.randint(0, 6) for _ in range(nin)]
        out.append((i, prog, nin, rng.randrange(0, 5), xs))
    return out


def test_random_terminating_programs(exe):
    rng = random.Random(20261005)
    done = skipped = 0
    batch = []
    for i, prog, nin, outv, xs in _fuzz_cases(rng, 220, wild=0.0):
        py = cs.interp(prog, xs, max_ops=4000, max_value=300)
        if py is None:
            skipped += 1
            continue
        batch.append((i, prog, nin, outv, xs, py))
    assert len(batch) >= 100, (len(batch), skipped)
    cases = [dict(id="r%d" % i, prog=prog, nin=nin, out=outv, xs=xs, ifuel=interp_fuel(prog, py[1]), hfuel=40_000_000)
             for i, prog, nin, outv, xs, py in batch]
    results = run_cases(exe, cases)
    nontrivial = 0
    for (i, prog, nin, outv, xs, py), res in zip(batch, results):
        check_against_python(res, prog, nin, outv, xs, py)
        msteps = check_vms(exe, res, prog, nin, outv, xs, "r%d" % i)
        record("fuzz%d" % i, xs, res, py[1], msteps)
        done += 1
        if py[1] > 5:
            nontrivial += 1
    assert done >= 100 and nontrivial >= 60


def test_random_programs_with_wild_loops(exe):
    """Loops that may not end. When the python interpreter finishes within its
    budget, everything must agree; when it does not, the runner either halts
    (and then agrees with a bigger python budget) or reports unhalted with
    all its fuel used."""
    rng = random.Random(4242)
    batch = []
    for i, prog, nin, outv, xs in _fuzz_cases(rng, 160, wild=0.35):
        py = cs.interp(prog, xs, max_ops=3000, max_value=300)
        batch.append((i, prog, nin, outv, xs, py))
    fin = [b for b in batch if b[5] is not None]
    inf = [b for b in batch if b[5] is None]
    assert len(fin) >= 40 and len(inf) >= 5, (len(fin), len(inf))
    hf = 2_000_000
    cases = [dict(id="w%d" % i, prog=prog, nin=nin, out=outv, xs=xs,
                  ifuel=interp_fuel(prog, py[1]) if py else 20000, hfuel=hf) for i, prog, nin, outv, xs, py in batch]
    results = run_cases(exe, cases)
    halted_wild = 0
    for (i, prog, nin, outv, xs, py), res in zip(batch, results):
        if py is not None:
            check_against_python(res, prog, nin, outv, xs, py)
        else:
            if res.halted:
                # the runner finished a program the small python budget did not: check with a big budget
                halted_wild += 1
                py2 = cs.interp(prog, xs, max_ops=10**8, max_value=10**15)
                assert py2 is not None
                assert res.vars == [py2[0].get(x, 0) for x in range(res.nv0)]
            else:
                assert res.steps == hf
                assert 1 <= res.pc <= res.host_len
    assert halted_wild >= 0


