@coq
def test_coq_vm_compute_agrees_on_small_cases(exe, tmp_path, request):
    coqc = ch.find_coqc()
    flags, why = ch.prebuilt_flags()
    if not coqc or flags is None:
        _missing(why or "coqc not found", request.config)
    entries = []
    for make, xs in [(cc.e_add, [3, 4]), (cc.e_mul_loop, [4, 5]), (cc.e_mul_call, [3, 3]), (cc.e_fact, [3]),
                     (cc.e_gcd, [6, 4]), (cc.e_prime, [11]), (cc.e_prime, [9]), (lambda: cc.e_ack(1), [2])]:
        name, prog, nin, out, ref = make()
        entries.append((name, prog, nin, out, xs))
    rng = random.Random(5)
    g = cc.Gen(rng, nvars=4)
    k = 0
    while k < 8:
        prog = g.program(2)
        xs = [rng.randint(0, 4), rng.randint(0, 4)]
        py = cs.interp(prog, xs, max_ops=300, max_value=40)
        if py is None:
            continue
        entries.append(("rand%d" % k, prog, 2, 1, xs))
        k += 1
    cases = []
    for name, prog, nin, out, xs in entries:
        py = cs.interp(prog, xs, max_ops=10**6)
        cases.append((prog, nin, out, xs, interp_fuel(prog, py[1]), 300000))
    got = ch.coq_eval_cases(coqc, flags, cases, tmp_path)
    ext = run_cases(exe, [dict(id=e[0], prog=e[1], nin=e[2], out=e[3], xs=e[4], ifuel=c[4], hfuel=c[5])
                          for e, c in zip(entries, cases)])
    for (name, prog, nin, out, xs), (wf, interp, run), r in zip(entries, got, ext):
        assert wf is True
        assert interp[0] is True and r.interp_ok
        assert interp[1] == r.interp_ops
        assert interp[2] == r.interp_vars
        halted, steps, answer, vars_ = run
        assert halted is True and r.halted
        assert steps == r.steps and answer == r.answer and vars_ == r.vars, name


