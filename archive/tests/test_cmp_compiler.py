def test_tiny_interpreter_random_machines(exe):
    """Random four-instruction machine programs, run by the compiled
    interpreter. The compiled code is fixed; the machine program is data."""
    name, prog, nin, out, ref = cc.e_tiny_interp()
    rng = random.Random(77)
    seen_halting = 0
    for _ in range(25):
        xs = []
        for _ in range(4):
            xs += [rng.randrange(0, 6), rng.randrange(0, 5)]
        xs += [rng.randrange(0, 6), rng.randrange(0, 6)]
        want = ref(*xs)
        if want is None:
            continue
        py = cs.interp(prog, xs, max_ops=10**6)
